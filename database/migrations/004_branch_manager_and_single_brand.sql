-- Adopt the customer / branch-manager / admin roles and singular brand table.
BEGIN;

ALTER TABLE hotel_brands RENAME TO hotel_brand;
ALTER TABLE hotel_brand ADD COLUMN logo_url TEXT;
ALTER TABLE branches DROP CONSTRAINT IF EXISTS branches_brand_id_fkey;
ALTER TABLE branches ALTER COLUMN brand_id DROP DEFAULT;
ALTER TABLE hotel_brand ALTER COLUMN id DROP DEFAULT;
ALTER TABLE hotel_brand ALTER COLUMN id TYPE BIGINT;
ALTER TABLE hotel_brand ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE hotel_brand ALTER COLUMN id RESTART WITH 2;
ALTER TABLE branches ALTER COLUMN brand_id TYPE BIGINT USING brand_id::BIGINT;
ALTER TABLE branches ALTER COLUMN brand_id SET DEFAULT 1;
ALTER TABLE branches ADD CONSTRAINT branches_brand_id_fkey
    FOREIGN KEY (brand_id) REFERENCES hotel_brand (id) ON DELETE RESTRICT;

UPDATE branches
SET partner_user_id = hotel_brand.owner_user_id
FROM hotel_brand
WHERE branches.partner_user_id IS NULL
  AND hotel_brand.id = 1
  AND hotel_brand.owner_user_id IS NOT NULL;

ALTER TABLE branches RENAME COLUMN partner_user_id TO manager_user_id;
DROP INDEX IF EXISTS branches_partner_user_id_idx;
CREATE INDEX branches_manager_user_id_idx ON branches (manager_user_id);

ALTER TABLE users DROP CONSTRAINT IF EXISTS users_role_check;
UPDATE users SET role = 'branch_manager' WHERE role = 'hotel_partner';
ALTER TABLE users ADD CONSTRAINT users_role_check
    CHECK (role IN ('customer', 'branch_manager', 'admin'));

ALTER TABLE hotel_brand DROP COLUMN owner_user_id;

COMMIT;
