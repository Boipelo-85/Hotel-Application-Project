-- Migration: Add room images, additional room fields, and room-specific amenities
-- This adds support for detailed room information as shown in the room details popup

-- Create room_images table first (doesn't require ALTER TABLE)
CREATE TABLE IF NOT EXISTS room_images (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id BIGINT NOT NULL REFERENCES rooms (id) ON DELETE CASCADE,
    image_url TEXT NOT NULL,
    alt_text TEXT,
    display_order INTEGER NOT NULL DEFAULT 0 CHECK (display_order >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS room_images_room_id_idx ON room_images (room_id, display_order);

-- Create room_amenities table for room-specific amenities
CREATE TABLE IF NOT EXISTS room_amenities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id BIGINT NOT NULL REFERENCES rooms (id) ON DELETE CASCADE,
    amenity_name TEXT NOT NULL,
    category TEXT NOT NULL CHECK (category IN ('bathroom', 'view', 'facilities', 'bedding', 'general')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (room_id, amenity_name, category)
);
CREATE INDEX IF NOT EXISTS room_amenities_room_id_idx ON room_amenities (room_id, category);

