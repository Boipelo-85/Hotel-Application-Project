CREATE TABLE IF NOT EXISTS booking_email_outbox (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    booking_id BIGINT NOT NULL REFERENCES bookings(id) ON DELETE RESTRICT,
    kind TEXT NOT NULL CHECK (kind IN ('confirmed', 'cancelled')),
    recipient TEXT NOT NULL,
    subject TEXT NOT NULL,
    body TEXT NOT NULL,
    attempts INTEGER NOT NULL DEFAULT 0,
    next_attempt_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    sent_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (booking_id, kind)
);
CREATE INDEX IF NOT EXISTS booking_email_outbox_pending_idx
    ON booking_email_outbox(next_attempt_at) WHERE sent_at IS NULL;
